#!/usr/bin/env python3
"""
Evaluate GameWorldScore rewards for rollouts generated by the *reference* (non-finetuned)
Oasis policy on the configured dataset.

This script:
- Loads config from YAML (same as train.py)
- Initializes a frozen OasisPolicy as a "reference" model
- Initializes GameWorldScoreReward using the reward section of the config
- Creates the dataset/dataloader using create_minecraft_dataloader
- For each batch:
    * Uses the first frame(s) and random actions to generate a short rollout
    * Computes per-frame GameWorldScore rewards
    * Aggregates and prints mean component rewards

Usage examples:

    # Use default config
    python eval_ref_policy_rewards.py

    # Custom config path
    python eval_ref_policy_rewards.py --config config/custom.yaml

    # Limit the number of batches evaluated
    python eval_ref_policy_rewards.py --max-batches 10

"""

import os
import sys
import argparse
from pathlib import Path
from typing import Dict, Any

import torch

# Add the oasis-finetuning directory to sys.path for proper imports
SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

from config.loader import load_config, DEFAULT_CONFIG_PATH
from models.oasis_policy import OasisPolicy
from rewards.game_world_score import create_game_world_score_reward
from data.minecraft_dataset import create_minecraft_dataloader


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Evaluate GameWorldScore rewards for reference Oasis policy rollouts",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    parser.add_argument(
        "--config", type=str, default=DEFAULT_CONFIG_PATH,
        help="Path to YAML config file (default: config/default.yaml)",
    )
    parser.add_argument(
        "--max-batches", type=int, default=10,
        help="Maximum number of batches to evaluate (0 = all)",
    )
    parser.add_argument(
        "--no-cuda", action="store_true",
        help="Force CPU even if CUDA is available",
    )

    return parser.parse_args()


def set_seed(seed: int) -> None:
    import random
    import numpy as np

    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


@torch.no_grad()
def evaluate_ref_policy(config, max_batches: int = 0) -> Dict[str, Any]:
    # Resolve device
    device = config.device
    if device == "cuda" and (not torch.cuda.is_available()):
        print("CUDA not available, falling back to CPU")
        device = "cpu"

    print("Initializing reference Oasis policy (non-finetuned)...")
    ref_policy = OasisPolicy(
        oasis_ckpt=config.oasis_ckpt,
        vae_ckpt=config.vae_ckpt,
        device=device,
        ddim_steps=config.ddim_steps,
    )
    ref_policy.eval_mode()
    for p in ref_policy.parameters():
        p.requires_grad = False

    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    # Initialize reward function
    print("Initializing GameWorldScore reward (for evaluation)...")
    reward_device = "cpu" if config.offload_reward_to_cpu else device
    reward_fn = create_game_world_score_reward(
        models_dir=config.reward_models_dir,
        device=reward_device,
        rik_weight=config.rik_weight,
        rtc_weight=config.rtc_weight,
        raq_weight=config.raq_weight,
        rrg_weight=config.rrg_weight,
        anti_drift_weight=config.anti_drift_weight,
        require_vpt=config.require_vpt,
    )

    # Build dataloader (same logic as trainer._init_dataloader)
    data_dir = Path(config.data_dir)
    if not data_dir.is_absolute():
        project_root = SCRIPT_DIR.parent.parent
        data_dir = project_root / config.data_dir

    if not data_dir.exists():
        raise FileNotFoundError(f"Data directory not found: {data_dir}")

    clip_length = config.n_prompt_frames + config.max_gen_frames
    print(f"Loading dataset from: {data_dir}")
    dataloader = create_minecraft_dataloader(
        data_dir=str(data_dir),
        batch_size=config.train_batch_size,
        clip_length=clip_length,
        dataset_type=config.dataset_type,
        frame_size=config.frame_size,
        split="train",
        num_workers=config.dataloader_num_workers,
    )

    all_metrics = {
        "game_world_score": [],
        "rik_reward": [],
        "rtc_reward": [],
        "raq_reward": [],
        "rrg_reward": [],
        "anti_drift_reward": [],
    }

    num_batches = 0

    for batch in dataloader:
        num_batches += 1

        # Handle both screenshots/midas (initial_frame) and video (frames)
        if "initial_frame" in batch:
            # Shape: (B, 1, C, H, W)
            initial_frames = batch["initial_frame"].to(device)
        elif "frames" in batch:
            # Old format: full sequence (B, T, C, H, W)
            frames = batch["frames"].to(device)
            # Use the first n_prompt_frames as context
            initial_frames = frames[:, : config.n_prompt_frames]
        else:
            raise ValueError("Batch does not contain 'initial_frame' or 'frames'")

        actions = batch["actions"].to(device)  # (B, T, action_dim)

        B, T_actions, _ = actions.shape
        num_gen = min(T_actions, config.max_gen_frames)

        # Generate rollouts with the reference policy
        generated_frames = ref_policy.generate_sequence(
            initial_frames=initial_frames,
            actions=actions[:, :num_gen],
            num_frames=num_gen,
        )  # (B, num_gen, C, H, W)

        # Concatenate context + generated frames
        if generated_frames.device != device:
            generated_frames = generated_frames.to(device)

        all_frames = torch.cat([initial_frames, generated_frames], dim=1)  # (B, 1+num_gen, C, H, W)
        actions_for_reward = actions[:, :num_gen]  # (B, num_gen, action_dim)

        # Move to reward device if necessary
        if reward_device == "cpu":
            frames_for_reward = all_frames.cpu()
            actions_for_reward = actions_for_reward.cpu()
        else:
            frames_for_reward = all_frames

        frame_rewards, info = reward_fn.compute_sequence_reward(
            frames_for_reward,
            actions_for_reward,
            return_per_frame=True,
        )  # frame_rewards: (B, num_gen)

        # Collect scalar metrics from info
        for key in all_metrics.keys():
            if key in info:
                all_metrics[key].append(info[key])

        print(
            f"Batch {num_batches}: "
            f"GWS={info.get('game_world_score', 0.0):.4f}, "
            f"RIK={info.get('rik_reward', 0.0):.4f}, "
            f"RTC={info.get('rtc_reward', 0.0):.4f}, "
            f"RAQ={info.get('raq_reward', 0.0):.4f}, "
            f"RRG={info.get('rrg_reward', 0.0):.4f}, "
            f"AD={info.get('anti_drift_reward', 0.0):.4f}"
        )

        # Optional: free memory between batches
        del generated_frames, all_frames, frames_for_reward, actions_for_reward, frame_rewards
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

        # Stop early if user requested max_batches
        if max_batches > 0 and num_batches >= max_batches:
            break

    # Aggregate metrics across batches
    summary = {}
    for key, values in all_metrics.items():
        if len(values) > 0:
            summary[key] = sum(values) / len(values)
        else:
            summary[key] = 0.0

    summary["num_batches"] = num_batches
    return summary


def main() -> None:
    args = parse_args()

    # Load config from YAML
    config = load_config(args.config)

    # Override device if requested
    if args.no_cuda:
        config.device = "cpu"

    # Use a fixed seed for reproducibility
    set_seed(42)

    print("=" * 60)
    print("Evaluating reference Oasis policy with GameWorldScore reward")
    print(f"Config: {args.config}")
    print("=" * 60)

    # Run evaluation loop and get aggregated metrics
    summary = evaluate_ref_policy(config, max_batches=args.max_batches)

    print("\nSummary over", summary.get("num_batches", 0), "batches:")
    print("  GameWorldScore:", f"{summary['game_world_score']:.4f}")
    print("  RIK:", f"{summary['rik_reward']:.4f}")
    print("  RTC:", f"{summary['rtc_reward']:.4f}")
    print("  RAQ:", f"{summary['raq_reward']:.4f}")
    print("  RRG:", f"{summary['rrg_reward']:.4f}")
    print("  Anti-Drift:", f"{summary['anti_drift_reward']:.4f}")


if __name__ == "__main__":
    main()
